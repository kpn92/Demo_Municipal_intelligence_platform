def _type_for(idx: int) -> tuple:
    r = idx % 20
    if r in (0, 1, 2, 3):
        return "recycling", 2500
    if r in (4, 5, 6):
        return "organic", 240
    return "mixed", 1100


def _fill_for(serial: int) -> int:
    return (serial * 13 + 7) % 97


def _status_for(serial: int) -> str:
    r = serial % 25
    if r == 24:
        return "offline"
    if r in (10, 20):
        return "issue"
    return "normal"


def generate_bins() -> list[dict]:
    bins = []
    for idx, (area_code, lng, lat) in enumerate(ROAD_COORDS):
        bin_type, capacity = _type_for(idx)
        bins.append({
            "bin_code": f"KHR-{idx + 1:04d}",
            "type": bin_type,
            "capacity": capacity,
            "area_code": area_code,
            "area_name": AREA_NAMES[area_code],
            "lng": lng,
            "lat": lat,
            "fill_level": _fill_for(idx),
            "status": _status_for(idx),
        })
    return bins


