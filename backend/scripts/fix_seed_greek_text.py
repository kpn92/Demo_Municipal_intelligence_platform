import json
import urllib.error
import urllib.request


BASE_URL = "http://127.0.0.1:8000/api/v1"


def request(method: str, path: str, payload: dict | None = None):
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload, ensure_ascii=True).encode("utf-8")
        headers["Content-Type"] = "application/json"

    req = urllib.request.Request(
        f"{BASE_URL}{path}",
        data=data,
        headers=headers,
        method=method,
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as response:
            body = response.read().decode("utf-8")
            return json.loads(body) if body else None
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8")
        raise RuntimeError(f"{method} {path} failed: {exc.code} {detail}") from exc


def get_all(path: str):
    return request("GET", path)


def update_by_code(path: str, code_field: str, code: str, payload: dict):
    existing = next(
        item for item in get_all(path)
        if item[code_field] == code
    )
    return request("PUT", f"{path}/{existing['id']}", payload)


def update_sector_item_by_name(current_name: str, payload: dict):
    existing = next(
        item for item in get_all("/sector-items")
        if item["name"] == current_name
    )
    return request("PUT", f"/sector-items/{existing['id']}", payload)


